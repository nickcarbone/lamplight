#!/usr/bin/env node
// LAMPLIGHT catalogue builder and validator. Node 18+, no dependencies.
//
//   node scripts/build-catalogue.mjs              merge sources + resolved snapshot + vetting -> catalogue.json
//   node scripts/build-catalogue.mjs --resolve    re-fetch archive.org metadata first (needs network)
//   node scripts/build-catalogue.mjs --check-links   range-request every MP3; write data/link-report.json
//
// The live page never calls LibriVox or archive.org APIs: it only reads catalogue.json
// and streams the MP3 URLs in it.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (f) => path.join(root, f);
const args = new Set(process.argv.slice(2));
const readJSON = async (f, fallback) => { try { return JSON.parse(await readFile(P(f), 'utf8')); } catch (e) { if (fallback !== undefined) return fallback; throw e; } };

const MIN_SECS = 7 * 60;   // spec says 8–45 min; a few gems run 7:30, so allow 7 and report them
const MAX_SECS = 45 * 60;
const MOODS = new Set(['calm', 'wistful', 'funny', 'eerie-but-soft']);
const LINKS = new Set(["author's home city", 'story is set here', 'tale from here', 'language of this place']);

const toSecs = (s) => { s = String(s ?? ''); if (/^\d+(\.\d+)?$/.test(s)) return Math.round(+s); return s.split(':').map(Number).reduce((a, b) => a * 60 + b, 0); };
const readerFrom = (desc) => {
  const d = String(desc || '').replace(/<[^>]+>/g, '\n');
  const m = d.match(/read (?:in [A-Za-z]+ )?by\s+([^\n]+?)(?:\.\s*(?=\n|$|[A-Z][a-z]+ [a-z])|\n|$)/i);
  if (m) return m[1].trim();
  // French LibriVox credits: "lu pour <a>Librivox</a> par Naf."
  const f = String(desc || '').replace(/<[^>]+>/g, '').match(/lu pour\s+librivox\s+par\s+([^\n.;,]+)/i);
  return f ? f[1].trim() : null;
};
const isSolo = (r) => r && !/volunteers|members|various|librivox|readers|;|,| and |&/i.test(r) && r.split(' ').length <= 5;
const lvFrom = (desc) => { const m = String(desc || '').match(/href="(https?:\/\/librivox\.org\/[^"]+)"/); return m ? m[1].replace(/^http:/, 'https:') : null; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchJSON(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    try { const r = await fetch(url, { headers: { 'User-Agent': 'lamplight-catalogue/1 (github.com/nickcarbone/lamplight)' } }); if (r.ok) return await r.json(); } catch {}
    await sleep(1500 * (i + 1));
  }
  throw new Error('fetch failed: ' + url);
}

async function resolve(sources) {
  const out = { _about: 'Snapshot of archive.org item metadata. Regenerated by scripts/build-catalogue.mjs --resolve.', resolvedAt: new Date().toISOString(), items: {} };
  const cache = new Map();
  for (const e of [...sources.entries, ...(sources.foreign || [])]) {
    try {
      if (!cache.has(e.ia)) cache.set(e.ia, await fetchJSON(`https://archive.org/metadata/${e.ia}`));
      const m = cache.get(e.ia);
      const rx = new RegExp(e.match, 'i');
      const files = (m.files || []).filter((f) => /_64kb\.mp3$/.test(f.name) && rx.test(f.title || '')).sort((a, b) => (+a.track || 0) - (+b.track || 0));
      out.items[e.key] = {
        reader: e.readerOverride || readerFrom(m.metadata?.description),
        librivox: lvFrom(m.metadata?.description),
        itemTitle: m.metadata?.title,
        parts: files.map((f) => [f.name, toSecs(f.length), f.title, f.creator || f.artist || null]),
      };
    } catch (err) { out.items[e.key] = { error: String(err) }; }
  }
  return out;
}

async function checkLinks(catalogue) {
  const report = { checkedAt: new Date().toISOString(), dead: [], ok: 0 };
  for (const s of [...catalogue.stories, ...(catalogue.foreign || [])]) {
    for (const p of s.parts) {
      let status = null;
      for (let i = 0; i < 3 && !(status >= 200 && status < 300); i++) {
        try { const r = await fetch(p.url, { headers: { Range: 'bytes=0-1' }, redirect: 'follow' }); status = r.status; try { await r.body?.cancel(); } catch {} } catch (e) { status = String(e); }
        if (!(status >= 200 && status < 300)) await sleep(2000 * (i + 1));
      }
      if (status >= 200 && status < 300) report.ok++; else report.dead.push({ id: s.id, title: s.title, url: p.url, status });
    }
  }
  return report;
}

function validTZ(tz) { try { new Intl.DateTimeFormat('en', { timeZone: tz }); return true; } catch { return false; } }

function build(sources, resolved, vetting) {
  const problems = [], warnings = [];
  const seen = new Set();
  const make = (e, kind) => {
    const r = resolved.items?.[e.key];
    const tag = `[${e.key}]`;
    if (seen.has(e.key)) problems.push(`${tag} duplicate key`); seen.add(e.key);
    if (!r || r.error) { problems.push(`${tag} not resolved: ${r?.error || 'missing from resolved.json'}`); return null; }
    if (!r.parts?.length) { problems.push(`${tag} no archive.org file matched /${e.match}/`); return null; }
    if (!isSolo(r.reader)) { problems.push(`${tag} reader not confirmed as a single named reader (got: ${r.reader})`); return null; }
    if (!validTZ(e.tz)) problems.push(`${tag} bad timezone ${e.tz}`);
    if (!(Math.abs(e.lat) <= 90 && Math.abs(e.lon) <= 180)) problems.push(`${tag} bad lat/lon`);
    if (!LINKS.has(e.link)) problems.push(`${tag} bad link type ${e.link}`);
    for (const m of e.mood || []) if (!MOODS.has(m)) problems.push(`${tag} bad mood ${m}`);
    if (!(e.mood || []).length) warnings.push(`${tag} no mood tag: content not checked`);
    if (kind === 'foreign' && !sources.languages?.[e.lang]) problems.push(`${tag} language ${e.lang} missing from "languages"`);
    const duration = r.parts.reduce((a, p) => a + p[1], 0);
    if (duration < MIN_SECS || duration > MAX_SECS) problems.push(`${tag} duration ${duration}s outside ${MIN_SECS}–${MAX_SECS}`);
    else if (duration < 8 * 60) warnings.push(`${tag} short: ${Math.round(duration / 6) / 10} min`);
    const v = vetting[e.key] || {};
    const out = {
      id: e.key, kind, title: e.title, author: e.author, origLang: e.origLang || e.lang, recLang: e.recLang || e.lang || 'en',
      reader: r.reader, librivox: r.librivox, ia: e.ia, iaTitle: r.itemTitle,
      parts: r.parts.map(([file, dur]) => ({ url: `https://archive.org/download/${e.ia}/${encodeURIComponent(file)}`, dur })),
      duration, place: e.place, country: e.country, lat: e.lat, lon: e.lon, tz: e.tz, link: e.link,
      genre: e.genre, mood: e.mood || [], hook: e.hook,
      status: v.status || 'unvetted', note: v.note || '',
    };
    if (kind === 'foreign') { out.titleEn = e.titleEn; out.lang = e.lang; out.langName = sources.languages[e.lang]; }
    else out.alternates = e.alternates || [];
    return out;
  };
  const stories = sources.entries.map((e) => make(e, 'story')).filter(Boolean);
  const foreign = (sources.foreign || []).map((e) => make(e, 'foreign')).filter(Boolean);
  return { problems, warnings, catalogue: { version: 2, generated: new Date().toISOString(), resolvedAt: resolved.resolvedAt, count: stories.length, stories, foreign, languages: sources.languages || {}, langByCountry: sources.langByCountry || {} } };
}

function coverage(stories) {
  // For each UTC hour, which stories' places are in local 21:00–23:59 (today's offsets)?
  const now = new Date();
  const hours = [];
  for (let h = 0; h < 24; h++) {
    const t = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate(), h, 30));
    const ids = stories.filter((s) => { const lh = +new Intl.DateTimeFormat('en-GB', { timeZone: s.tz, hour: '2-digit', hourCycle: 'h23' }).format(t); return lh >= 21 && lh <= 23; });
    hours.push({ utc: h, n: ids.length, places: [...new Set(ids.map((s) => s.place))] });
  }
  return hours;
}

const sources = await readJSON('data/sources.json');
let resolved = await readJSON('data/resolved.json', { items: {} });
const vetting = await readJSON('data/vetting.json', {});

if (args.has('--resolve')) {
  resolved = await resolve(sources);
  await writeFile(P('data/resolved.json'), JSON.stringify(resolved, null, 1) + '\n');
  console.log('resolved', Object.keys(resolved.items).length, 'entries from archive.org');
}

if (args.has('--check-links')) {
  const cat = await readJSON('catalogue.json');
  const report = await checkLinks(cat);
  await writeFile(P('data/link-report.json'), JSON.stringify(report, null, 1) + '\n');
  console.log(`links ok: ${report.ok}, dead: ${report.dead.length}`);
  for (const d of report.dead) console.log(`DEAD ${d.id} ${d.status} ${d.url}`);
  process.exit(report.dead.length ? 2 : 0);
}

const { problems, warnings, catalogue } = build(sources, resolved, vetting);
for (const w of warnings) console.warn('warn', w);
if (problems.length) { for (const p of problems) console.error('ERROR', p); }
await writeFile(P('catalogue.json'), JSON.stringify(catalogue, null, 1) + '\n');

const byCountry = {}; for (const s of catalogue.stories) byCountry[s.country] = (byCountry[s.country] || 0) + 1;
const cov = coverage(catalogue.stories);
console.log(`catalogue: ${catalogue.count} stories, ${Object.keys(byCountry).length} countries`);
const byLang = {}; for (const f of catalogue.foreign) byLang[f.langName] = (byLang[f.langName] || 0) + 1;
console.log(`foreign-language pieces: ${catalogue.foreign.length} (` + Object.entries(byLang).map(([l, n]) => `${l} ${n}`).join(', ') + ')');
const uncovered = Object.entries(catalogue.langByCountry).filter(([c, ls]) => !catalogue.foreign.some((f) => ls.includes(f.lang))).map(([c]) => c);
console.log('countries using the nearest-language fallback: ' + uncovered.join(', '));
console.log('by country:', Object.entries(byCountry).sort((a, b) => b[1] - a[1]).map(([c, n]) => `${c} ${n}`).join(', '));
console.log('UTC-hour coverage (local 21:00–23:59):');
for (const h of cov) console.log(`  ${String(h.utc).padStart(2, '0')}:30Z  ${String(h.n).padStart(2)}  ${h.places.join(', ')}`);
if (args.has('--strict') && problems.length) process.exit(1);
